#!/usr/bin/env bash
#
# Generates Codex's custom subagents from the shared subagent sources.
#
#   setup/codex-agents.sh [--source DIR] [--dest DIR]
#
# Claude Code and pi read subagents/<name>.md (YAML frontmatter plus a markdown
# prompt) through symlinks. Codex reads ~/.codex/agents/<name>.toml
# instead (`name`, `description` and `developer_instructions` are required), so
# it cannot share the files by link: this converts each source into a TOML file.
#
# Mapping: name and description carry over; the markdown body becomes
# developer_instructions; `tools` has no Codex equivalent except that a
# subagent with neither Write nor Edit gets sandbox_mode = "read-only"; `model`
# is dropped, because Claude model names mean nothing to Codex, which then uses
# its own default.
#
# Every generated file starts with a marker line. Only marked files are ever
# rewritten or removed: a file of the same name without the marker belongs to
# someone else, so it is left alone with a warning, and the subagent of that
# name is not shared until it is moved away. Generated files whose source is
# gone are deleted.
#
# Exit status: 0 on success, 3 when something was skipped (a warning has been
# printed), 2 for bad usage.

set -euo pipefail

MARKER="# Generated by devtools setup/codex-agents.sh from subagents/ - do not edit; edit the source."
# Files generated before the sources moved out of home/.pi/agent/agents carry
# this marker; they are still ours, and are rewritten with the current one.
LEGACY_MARKER="# Generated by devtools setup/codex-agents.sh from home/.pi/agent/agents - do not edit; edit the source."
is_ours() { [ "$(head -n1 "$1")" = "$MARKER" ] || [ "$(head -n1 "$1")" = "$LEGACY_MARKER" ]; }

source_dir=""
dest_dir="${HOME}/.codex/agents"
while [ $# -gt 0 ]; do
  case "$1" in
  --source) source_dir="${2:?--source needs a value}"; shift 2 ;;
  --dest) dest_dir="${2:?--dest needs a value}"; shift 2 ;;
  -h | --help) sed -n '3,22p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) echo "Error: unknown argument '$1'." >&2; exit 2 ;;
  esac
done
[ -n "$source_dir" ] || source_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/subagents"
[ -d "$source_dir" ] || { echo "Error: $source_dir is not a directory." >&2; exit 2; }

warned=0
warn() { warned=1; echo "    WARNING: codex agents: $*" >&2; }

# Read one frontmatter field, YAML double-quoted, single-quoted or plain, and
# print it as a TOML basic string.
field() {
  awk -v key="$1" '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && index($0, key ":") == 1 {
      v = substr($0, length(key) + 2); sub(/^ +/, "", v); sub(/ +$/, "", v)
      if (v ~ /^".*"$/) { print v; exit }
      if (v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
      gsub(/\\/, "\\\\", v); gsub(/"/, "\\\"", v)
      print "\"" v "\""; exit
    }' "$2"
}

mkdir -p "$dest_dir"
declare -a kept=()
for src in "$source_dir"/*.md; do
  [ -f "$src" ] || continue
  base="$(basename "$src" .md)"
  out="$dest_dir/$base.toml"
  name="$(field name "$src")"
  desc="$(field description "$src")"
  tools="$(awk 'NR == 1 && $0 == "---" { fm = 1; next } fm && $0 == "---" { exit } fm && /^tools:/' "$src")"
  body="$(awk 'c >= 2 { print; next } $0 == "---" { c++ }' "$src")"

  if [ -z "$name" ] || [ -z "$desc" ] || [ -z "${body//[[:space:]]/}" ]; then
    warn "$src needs name, description and a body; skipped"
    continue
  fi
  if [[ "$body" == *"'''"* ]]; then
    warn "$src contains ''' which a TOML literal string cannot hold; skipped"
    continue
  fi
  if [ -e "$out" ] && ! is_ours "$out"; then
    warn "$out exists and is not generated by this script; left alone, so '$base' is not shared with Codex"
    continue
  fi

  tmp="$out.new"
  {
    echo "$MARKER"
    echo "name = $name"
    echo "description = $desc"
    case "$tools" in
    *Write* | *Edit*) ;;
    *) echo 'sandbox_mode = "read-only"' ;;
    esac
    echo "developer_instructions = '''"
    printf '%s\n' "$body"
    echo "'''"
  } >"$tmp"
  if [ -f "$out" ] && cmp -s "$tmp" "$out"; then rm -f "$tmp"; else mv -f "$tmp" "$out"; fi
  kept+=("$base.toml")
done

# Drop generated files whose source is gone.
for out in "$dest_dir"/*.toml; do
  [ -f "$out" ] || continue
  is_ours "$out" || continue
  keep=0
  for k in ${kept[@]+"${kept[@]}"}; do [ "$k" = "$(basename "$out")" ] && keep=1; done
  [ "$keep" -eq 1 ] || rm -f "$out"
done

echo "    codex agents: ${#kept[@]} generated in $dest_dir"
[ "$warned" -eq 0 ] || exit 3
