#!/usr/bin/env bash
#
# Generates every tool's subagent files from the tool-neutral sources.
#
#   setup/subagents.sh [--source DIR] [--home DIR]
#
# subagents/<name>.md holds what is the same everywhere: `name`, `description`
# and the prompt body. subagents/layers/<tool>.yaml holds what differs per
# tool: one block per agent, keyed by agent name, with its settings (model, tool
# list, sandbox) as scalar keys. This script reads them with mikefarah yq (pinned
# in home.nix and installed by setup/windows.sh) and combines the two into:
#
#   claude  ~/.claude/agents/<name>.md      frontmatter + body
#   pi      ~/.pi/agent/agents/<name>.md    frontmatter + body (pi's own tool names)
#   codex   ~/.codex/agents/<name>.toml     name, description, developer_instructions
#
# Layer keys become `key: value` frontmatter for claude and pi, and
# `key = "value"` for codex. `skip: true` in an agent's block keeps that agent
# out of that tool. The files are generated, not linked, because no single frontmatter fits
# all tools: Claude Code and pi name tools differently, and Codex takes TOML and
# no Anthropic model names.
#
# Every generated file carries a marker (a YAML comment on line 2 of the markdown
# files, line 1 of the TOML). Only marked files are ever rewritten or removed.
# A file of the same name without the marker belongs to someone else and is left
# exactly as it is, without a warning per file; the summary line counts them.
# Generated files whose source is gone, or whose agent is skipped, are deleted.
#
# Exit status: 0 on success, 3 when a source was skipped (a warning has been
# printed), 2 for bad usage.

set -euo pipefail

MARKER="# Generated by devtools setup/subagents.sh from subagents/ - do not edit; edit the source."
# Codex files generated before the sources moved out of home/.pi/agent/agents
# carry this marker; they are still ours, and are rewritten with the current one.
LEGACY_MARKER="# Generated by devtools setup/codex-agents.sh from home/.pi/agent/agents - do not edit; edit the source."

command -v yq >/dev/null 2>&1 || { echo "Error: subagents: yq (mikefarah) is required to read the layers and is not on PATH." >&2; exit 2; }

source_dir=""
home_dir="$HOME"
while [ $# -gt 0 ]; do
  case "$1" in
  --source) source_dir="${2:?--source needs a value}"; shift 2 ;;
  --home) home_dir="${2:?--home needs a value}"; shift 2 ;;
  -h | --help) sed -n '3,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) echo "Error: unknown argument '$1'." >&2; exit 2 ;;
  esac
done
[ -n "$source_dir" ] || source_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/subagents"
[ -d "$source_dir" ] || { echo "Error: $source_dir is not a directory." >&2; exit 2; }

# A layer that does not parse must stop the run: reading it as empty would
# generate every agent without its model, tool list or read-only sandbox.
for layer in "$source_dir"/layers/*.yaml; do
  [ -f "$layer" ] || continue
  yq -e '. == null or tag == "!!map"' "$layer" >/dev/null 2>&1 ||
    { echo "Error: $layer is not valid YAML or not a map of agents." >&2; exit 2; }
done

warned=0
warn() { warned=1; echo "    WARNING: subagents: $*" >&2; }

# Whether $1 is a regular file this script generated: the marker is line 2 of a
# markdown file and line 1 of a TOML file.
is_ours() {
  [ -f "$1" ] && [ ! -L "$1" ] || return 1
  case "$1" in
  *.toml) [ "$(head -n1 "$1")" = "$MARKER" ] || [ "$(head -n1 "$1")" = "$LEGACY_MARKER" ] ;;
  *) [ "$(sed -n 2p "$1")" = "$MARKER" ] ;;
  esac
}

# The settings of a layer for one agent, as `key value` lines. `skip: true`
# comes out as the line `skip true`; `skip: false` is the same as no skip.
layer_lines() {
  local file="$source_dir/layers/$1.yaml"
  [ -f "$file" ] || return 0
  # shellcheck disable=SC2016 # strenv is yq syntax
  AGENT="$2" yq -r '
    (.[strenv(AGENT)] // {}) | to_entries | .[]
    | (.key + " " + (.value | tostring)) | select(. != "skip false")' "$file"
}

# Frontmatter lines (between the first two `---`) and body (after them).
frontmatter() { awk 'NR == 1 && $0 == "---" { fm = 1; next } fm && $0 == "---" { exit } fm' "$1"; }
body_of() { awk 'c >= 2 { print; next } $0 == "---" { c++ }' "$1"; }

# One frontmatter value as a TOML basic string, whether the source wrote it
# YAML double-quoted, single-quoted or plain.
toml_field() {
  frontmatter "$2" | awk -v key="$1" '
    index($0, key ":") == 1 {
      v = substr($0, length(key) + 2); sub(/^ +/, "", v); sub(/ +$/, "", v)
      if (v ~ /^".*"$/) { print v; exit }
      if (v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
      gsub(/\\/, "\\\\", v); gsub(/"/, "\\\"", v)
      print "\"" v "\""; exit
    }'
}

# Write $2 to $1 unless it is already identical.
install_file() {
  if [ -f "$1" ] && cmp -s "$2" "$1"; then rm -f "$2"; else mv -f "$2" "$1"; fi
}

generate_markdown() { # tool dest
  local tool="$1" dest="$2" src base out lines tmp
  mkdir -p "$dest"
  declare -a kept=()
  local generated=0 foreign=0 skipped=0
  for src in "$source_dir"/*.md; do
    [ -f "$src" ] || continue
    base="$(basename "$src" .md)"
    out="$dest/$base.md"
    lines="$(layer_lines "$tool" "$base")"
    if grep -qx 'skip true' <<<"$lines"; then skipped=$((skipped + 1)); continue; fi
    if [ -z "$(frontmatter "$src")" ] || [ -z "$(body_of "$src" | tr -d '[:space:]')" ]; then
      warn "$src needs frontmatter and a body; skipped for $tool"
      continue
    fi
    if [ -e "$out" ] || [ -L "$out" ]; then
      if ! is_ours "$out"; then foreign=$((foreign + 1)); continue; fi
    fi
    tmp="$out.new"
    {
      echo "---"
      echo "$MARKER"
      frontmatter "$src"
      [ -z "$lines" ] || awk '{ k = $1; sub(/^[^ ]+ +/, ""); print k ": " $0 }' <<<"$lines"
      echo "---"
      body_of "$src"
    } >"$tmp"
    install_file "$out" "$tmp"
    kept+=("$base.md")
    generated=$((generated + 1))
  done
  prune "$dest" md "${kept[@]+"${kept[@]}"}"
  summary "$tool" "$dest" "$generated" "$foreign" "$skipped"
}

generate_codex() { # dest
  local tool=codex dest="$1" src base out lines name desc tmp key val
  mkdir -p "$dest"
  declare -a kept=()
  local generated=0 foreign=0 skipped=0
  for src in "$source_dir"/*.md; do
    [ -f "$src" ] || continue
    base="$(basename "$src" .md)"
    out="$dest/$base.toml"
    lines="$(layer_lines "$tool" "$base")"
    if grep -qx 'skip true' <<<"$lines"; then skipped=$((skipped + 1)); continue; fi
    name="$(toml_field name "$src")"
    desc="$(toml_field description "$src")"
    if [ -z "$name" ] || [ -z "$desc" ] || [ -z "$(body_of "$src" | tr -d '[:space:]')" ]; then
      warn "$src needs name, description and a body; skipped for codex"
      continue
    fi
    if [[ "$(body_of "$src")" == *"'''"* ]]; then
      warn "$src contains ''' which a TOML literal string cannot hold; skipped for codex"
      continue
    fi
    if [ -e "$out" ] || [ -L "$out" ]; then
      if ! is_ours "$out"; then foreign=$((foreign + 1)); continue; fi
    fi
    tmp="$out.new"
    {
      echo "$MARKER"
      echo "name = $name"
      echo "description = $desc"
      while read -r key val; do
        [ -n "$key" ] || continue
        printf '%s = "%s"\n' "$key" "${val//\"/\\\"}"
      done <<<"$lines"
      echo "developer_instructions = '''"
      body_of "$src"
      echo "'''"
    } >"$tmp"
    install_file "$out" "$tmp"
    kept+=("$base.toml")
    generated=$((generated + 1))
  done
  prune "$dest" toml "${kept[@]+"${kept[@]}"}"
  summary "$tool" "$dest" "$generated" "$foreign" "$skipped"
}

# Drop generated files whose source is gone or whose agent is now skipped.
prune() { # dest ext kept...
  local dest="$1" ext="$2" out k keep
  shift 2
  for out in "$dest"/*."$ext"; do
    [ -f "$out" ] || continue
    is_ours "$out" || continue
    keep=0
    for k in "$@"; do [ "$k" = "$(basename "$out")" ] && keep=1; done
    [ "$keep" -eq 1 ] || rm -f "$out"
  done
}

summary() { # tool dest generated foreign skipped
  local line="    subagents ($1): $3 generated in $2"
  [ "$4" -eq 0 ] || line="$line, $4 existing files left alone"
  [ "$5" -eq 0 ] || line="$line, $5 skipped by the layer"
  echo "$line"
}

generate_markdown claude "$home_dir/.claude/agents"
generate_markdown pi "$home_dir/.pi/agent/agents"
generate_codex "$home_dir/.codex/agents"

[ "$warned" -eq 0 ] || exit 3
